#!/usr/bin/env python3
"""Prepare a SMASH-Pull setup for external MD programs.

    python prepare.py pull_setup.json

Fetches the structure (RCSB PDB, AlphaFold DB or a local file), selects the
chain / residue window with the SMASH-Pull rules, and writes, next to the setup:

  structure.pdb            the downloaded file (cache)
  prepared_allatom.pdb     the selected protein atoms, anchor Cα at the origin,
                           pull direction along +z (HETATM, waters removed)
  prepared_ca.pdb          the Cα trace in the same frame
  prepared.json            residues, distances, box sizes, warnings
  gromacs/                 .mdp files and run.sh for a GROMACS steered-MD pull

Standard library only.
"""
from __future__ import annotations

import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import smashpull as sp  # noqa: E402


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    path = sys.argv[1]
    setup = sp.load_setup(path)
    wd = sp.setup_dir(path)
    st = setup["structure"]
    text = sp.fetch_structure(st, wd)
    atoms, chain, notes = sp.parse_atoms(text, st.get("chain"), st.get("range"))
    residues, ca, bfac = sp.ca_trace(atoms)
    ar = setup.get("anchor", {}).get("residue") or residues[0]
    pr = setup.get("pulled", {}).get("residue") or residues[-1]
    for r in (ar, pr):
        if r not in residues:
            raise SystemExit(f"residue {r} is not in chain {chain} ({residues[0]}..{residues[-1]})")
    ia, ip = residues.index(ar), residues.index(pr)
    d0 = sp.align(atoms, ca[ia], ca[ip])
    _, ca2, _ = sp.ca_trace(atoms)
    het = sum(1 for l in text.splitlines() if l.startswith("HETATM"))
    if het:
        notes.append(f"{het} HETATM record(s) removed (ligands, ions, waters); add them back by hand if they matter")
    gaps = [(residues[k], residues[k + 1]) for k in range(len(residues) - 1) if residues[k + 1] - residues[k] != 1]
    if gaps:
        notes.append(f"{len(gaps)} gap(s) in residue numbering {gaps[:5]}: all-atom tools will not bridge them; model the loops first")
    ssbond = [l for l in text.splitlines() if l.startswith("SSBOND")]
    if ssbond:
        notes.append(f"{len(ssbond)} SSBOND record(s): disulfides are kept by pdb2gmx/OpenMM if CYS SG atoms are close")
    afold = sp.is_alphafold(text)
    sep = abs(ip - ia)
    contour_nm = 0.38 * sep
    xs, ys, zs = [a["x"] for a in atoms], [a["y"] for a in atoms], [a["z"] for a in atoms]
    aa = setup.get("all_atom", {})
    pad = aa.get("padding_nm", 1.2)
    dist_nm = aa.get("pull_distance_nm") or round(max(1.0, 0.8 * (contour_nm - d0 / 10)), 2)
    ext = [(max(v) - min(v)) / 10 for v in (xs, ys, zs)]
    box = [round(ext[0] + 2 * pad, 2), round(ext[1] + 2 * pad, 2), round(ext[2] + dist_nm + 2 * pad, 2)]
    center = [round(box[0] / 2 - (max(xs) + min(xs)) / 20, 3), round(box[1] / 2 - (max(ys) + min(ys)) / 20, 3),
              round(pad - min(zs) / 10, 3)]  # translation applied to the prepared frame
    remarks = [f"SMASH-Pull prepared {setup.get('name', '')}", f"source {st['source']} {st.get('id', st.get('file'))} chain {chain}",
               f"anchor CA {ar} at origin; pulled CA {pr} on +z at {d0:.2f} A"]
    sp.write_pdb(atoms, os.path.join(wd, "prepared_allatom.pdb"), remarks=remarks)
    sp.write_pdb([a for a in atoms if a["name"] == "CA"], os.path.join(wd, "prepared_ca.pdb"), remarks=remarks)
    info = {
        "name": setup.get("name"), "chain": chain, "residues": [residues[0], residues[-1]], "n_residues": len(residues),
        "anchor_residue": ar, "pulled_residue": pr, "anchor_pulled_distance_A": round(d0, 3),
        "contour_nm": round(contour_nm, 2), "pull_distance_nm": dist_nm, "is_alphafold": afold,
        "mean_bfactor_or_plddt": round(sum(bfac) / len(bfac), 2),
        "box_nm": box, "box_translation_nm": center, "notes": notes,
    }
    with open(os.path.join(wd, "prepared.json"), "w", encoding="utf-8") as fh:
        json.dump(info, fh, indent=1)
    write_gromacs(setup, info, os.path.join(wd, "gromacs"))
    print(f"{setup.get('name', '')}: chain {chain}, {len(residues)} residues, pulling {ar} -> {pr} ({d0 / 10:.2f} nm apart, contour {contour_nm:.1f} nm)")
    print(f"all-atom pull distance {dist_nm} nm; box {box} nm")
    for n in notes:
        print("  note:", n)
    print("next: python openmm_go.py", os.path.basename(path), " |  python openmm_allatom.py", os.path.basename(path), " |  bash gromacs/run.sh")


MDP_COMMON = """; generated by SMASH-Pull prepare.py
cutoff-scheme       = Verlet
nstlist             = 20
pbc                 = xyz
coulombtype         = PME
rcoulomb            = 1.0
rvdw                = 1.0
DispCorr            = EnerPres
"""


def write_gromacs(setup, info, out):
    os.makedirs(out, exist_ok=True)
    aa = setup.get("all_atom", {})
    T = setup.get("conditions", {}).get("temperature_K", 300)
    conc = setup.get("conditions", {}).get("ionic_strength_M", 0.15)
    dt = aa.get("timestep_fs", 2) / 1000.0
    rate = aa.get("speed_nm_per_ns", 2.0) / 1000.0  # nm/ps
    k = aa.get("spring_k_kJ_mol_nm2", 1000)
    eq_steps = int(round(aa.get("equilibration_ns", 0.5) * 1000 / dt / 2))
    pull_steps = int(math.ceil(info["pull_distance_nm"] / rate / dt))
    ff = aa.get("gromacs_forcefield", "amber99sb-ildn")
    water = aa.get("gromacs_water", "tip3p")
    tc = f"""tcoupl              = V-rescale
tc-grps             = Protein Non-Protein
tau-t               = 0.1 0.1
ref-t               = {T} {T}
constraints         = h-bonds
constraint-algorithm = lincs
"""
    files = {
        "ions.mdp": MDP_COMMON + "integrator = steep\nemtol = 1000.0\nemstep = 0.01\nnsteps = 50000\n",
        "em.mdp": MDP_COMMON + "integrator = steep\nemtol = 1000.0\nemstep = 0.01\nnsteps = 50000\n",
        "nvt.mdp": MDP_COMMON + tc + f"""define              = -DPOSRES
integrator          = md
dt                  = {dt}
nsteps              = {eq_steps}
nstxout-compressed  = 5000
nstenergy           = 1000
nstlog              = 1000
gen-vel             = yes
gen-temp            = {T}
gen-seed            = -1
pcoupl              = no
""",
        "npt.mdp": MDP_COMMON + tc + f"""define              = -DPOSRES
integrator          = md
dt                  = {dt}
nsteps              = {eq_steps}
nstxout-compressed  = 5000
nstenergy           = 1000
nstlog              = 1000
continuation        = yes
gen-vel             = no
pcoupl              = C-rescale
pcoupltype          = isotropic
tau-p               = 2.0
ref-p               = 1.0
compressibility     = 4.5e-5
refcoord-scaling    = com
""",
        "pull.mdp": MDP_COMMON + tc + f"""; constant-velocity pull of residue {info['pulled_residue']} (CA) away from residue {info['anchor_residue']} (CA) along +z
define              = -DPOSRES_ANCHOR
integrator          = md
dt                  = {dt}
nsteps              = {pull_steps}          ; {info['pull_distance_nm']} nm at {aa.get('speed_nm_per_ns', 2.0)} nm/ns
nstxout-compressed  = 5000
compressed-x-grps   = Protein
nstenergy           = 1000
nstlog              = 1000
continuation        = yes
gen-vel             = no
pcoupl              = no
pull                = yes
pull-ncoords        = 1
pull-ngroups        = 2
pull-group1-name    = Anchor
pull-group2-name    = Pulled
pull-coord1-type    = umbrella
pull-coord1-geometry = direction-periodic
pull-coord1-vec     = 0 0 1
pull-coord1-groups  = 1 2
pull-coord1-start   = yes
pull-coord1-rate    = {rate}
pull-coord1-k       = {k}
pull-nstxout        = 50
pull-nstfout        = 50
""",
    }
    bx, by, bz = info["box_nm"]
    tx, ty, tz = info["box_translation_nm"]
    run = f"""#!/usr/bin/env bash
# SMASH-Pull GROMACS steered-MD pull: {setup.get('name', '')}
# Requires GROMACS 2021+ (`gmx`). Run from this folder:  bash run.sh
# Box {bx} x {by} x {bz} nm: room to pull {info['pull_distance_nm']} nm along +z.
set -euo pipefail
GMX=${{GMX:-gmx}}
$GMX pdb2gmx -f ../prepared_allatom.pdb -o processed.gro -p topol.top -i posre.itp -ff {ff} -water {water} -ignh
$GMX editconf -f processed.gro -o boxed.gro -box {bx} {by} {bz} -translate {tx} {ty} {tz} -noc
$GMX solvate -cp boxed.gro -cs spc216.gro -o solv.gro -p topol.top
$GMX grompp -f ions.mdp -c solv.gro -p topol.top -o ions.tpr -maxwarn 1
echo SOL | $GMX genion -s ions.tpr -o solv_ions.gro -p topol.top -pname NA -nname CL -neutral -conc {conc}
$GMX grompp -f em.mdp -c solv_ions.gro -p topol.top -o em.tpr
$GMX mdrun -deffnm em
# index: default groups + the two pulled Cα atoms
echo q | $GMX make_ndx -f em.gro -o index.ndx
$GMX select -s em.tpr -on pullgroups.ndx -select '"Anchor" resnr {info['anchor_residue']} and name CA; "Pulled" resnr {info['pulled_residue']} and name CA'
cat pullgroups.ndx >> index.ndx
# position restraint on the anchor Cα only, switched on in the pull run (-DPOSRES_ANCHOR)
echo Anchor | $GMX genrestr -f em.gro -n index.ndx -o posre_anchor.itp -fc 10000 10000 10000
sed -i '/; Include water topology/i #ifdef POSRES_ANCHOR\\n#include "posre_anchor.itp"\\n#endif\\n' topol.top
$GMX grompp -f nvt.mdp -c em.gro -r em.gro -p topol.top -n index.ndx -o nvt.tpr
$GMX mdrun -deffnm nvt
$GMX grompp -f npt.mdp -c nvt.gro -r nvt.gro -t nvt.cpt -p topol.top -n index.ndx -o npt.tpr
$GMX mdrun -deffnm npt
$GMX grompp -f pull.mdp -c npt.gro -r npt.gro -t npt.cpt -p topol.top -n index.ndx -o pull.tpr
$GMX mdrun -deffnm pull -pf pullf.xvg -px pullx.xvg
echo "done: pullf.xvg (force, kJ/mol/nm; x 1.6605 = pN) and pullx.xvg (position, nm)"
"""
    for name, body in files.items():
        with open(os.path.join(out, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(body)
    with open(os.path.join(out, "run.sh"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(run)


if __name__ == "__main__":
    main()
