// SMASH-BIO data viewer: harmonised traces from data/viewer/*.json, plus local files parsed in the browser.
'use strict';
(function () {
  const $ = id => document.getElementById(id);
  const C = window.PullChart;
  const esc = s => String(s ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  let index = null, ds = null, axes = 'fx', hidden = new Set();

  // ------------------------------------------------------------ tabs
  document.querySelectorAll('.tabs button').forEach(b => b.onclick = () => {
    b.parentElement.querySelectorAll('button').forEach(x => { x.setAttribute('aria-selected', x === b); $(x.dataset.tab).hidden = x !== b; });
  });

  // ------------------------------------------------------------ datasets
  const statusBadge = d => d.status === 'traces' ? `<span class="badge badge-good">${d.n_traces} traces</span>`
    : d.status === 'metadata_only' ? '<span class="badge badge-warn">link only (licence)</span>' : '<span class="badge">not yet harmonised</span>';
  async function loadIndex() {
    try { index = await (await fetch('data/viewer/index.json')).json(); } catch (e) { $('ds-list').innerHTML = '<p class="status err">Could not load the dataset index.</p>'; return; }
    const order = { traces: 0, not_harmonised: 1, metadata_only: 2 };
    const list = [...index.datasets].sort((a, b) => order[a.status] - order[b.status]);
    $('ds-list').innerHTML = list.map(d => `<button class="chip" style="display:block;width:100%;text-align:left;margin-bottom:6px;border-radius:10px;padding:8px 10px" data-key="${esc(d.key)}">
      <strong style="display:block">${esc(d.ligand || 'no ligand')} · ${esc((d.technique || '').replace(/_/g, ' '))}</strong>
      <span class="small">${esc((d.title || '').slice(0, 90))}</span><br>${statusBadge(d)}</button>`).join('');
    $('ds-list').querySelectorAll('[data-key]').forEach(b => b.onclick = () => openDataset(b.dataset.key));
    const want = new URLSearchParams(location.hash.slice(1)).get('ds') || (list.find(d => d.status === 'traces') || list[0]).key;
    openDataset(want);
  }
  async function openDataset(key) {
    ds = await (await fetch(`data/viewer/${encodeURIComponent(key)}.json`)).json();
    hidden = new Set();
    history.replaceState(null, '', '#ds=' + encodeURIComponent(key));
    const papers = (ds.paper_dois || []).map(d => `<a href="https://doi.org/${esc(d)}" target="_blank" rel="noopener">${esc(d)}</a>`).join(', ');
    $('ds-head').innerHTML = `<h2 style="font-size:1.15rem;margin:0 0 6px">${esc(ds.title)}</h2>
      <p class="small muted" style="margin:0 0 8px">${esc((ds.authors || []).join('; '))}</p>
      <dl class="kv">
        <div><dt>Ligand / drug</dt><dd>${esc(ds.ligand || 'none')}</dd></div>
        <div><dt>Technique</dt><dd>${esc((ds.technique || '').replace(/_/g, ' '))}</dd></div>
        <div><dt>Source</dt><dd><a href="${esc(ds.url)}" target="_blank" rel="noopener">${esc(ds.repository)} ${esc(ds.record_id)}</a></dd></div>
        <div><dt>Licence</dt><dd>${esc(ds.license || 'unknown')}</dd></div>
      </dl>${papers ? `<p class="small" style="margin:8px 0 0">Paper: ${papers}. Cite the original authors when using these data.</p>` : '<p class="small" style="margin:8px 0 0">Cite the original authors and the deposit when using these data.</p>'}
      ${ds.problems.length ? `<ul class="notes">${ds.problems.slice(0, 6).map(p => `<li>${esc(p)}</li>`).join('')}</ul>` : ''}`;
    const has = ds.traces.length > 0;
    $('ds-plot-panel').hidden = !has; $('ds-prov').hidden = !ds.files.length;
    if (has) {
      const hasT = ds.traces.some(t => t.t);
      document.querySelectorAll('#axes button').forEach(b => { b.disabled = b.dataset.v !== 'fx' && !hasT; });
      if (!hasT) axes = 'fx';
      setAxes(axes);
    }
    $('prov').innerHTML = `<div class="table-wrap"><table class="pull-table"><thead><tr><th>File in deposit</th><th>Condition (evidence)</th><th>Reader</th><th>Traces</th><th>sha256</th></tr></thead><tbody>${ds.files.map(f => `<tr><td class="small">${esc(f.path_in_deposit)}</td><td class="small"><strong>${esc(f.condition.label)}</strong> (${esc(f.condition.role)})<br><span class="muted">${esc(f.condition.evidence)}</span></td><td class="small">${esc(f.format)}</td><td class="n">${f.n_traces}</td><td class="small mono">${esc(f.sha256.slice(0, 12))}…</td></tr>`).join('')}</tbody></table></div>
      ${ds.reader_choice ? `<p class="hint">Channel choice: ${esc(ds.reader_choice)}</p>` : ''}
      <p class="hint">${esc(index.display_downsampling)}. Generated by ${esc(index.generated_by)}.</p>`;
  }
  function conditions() {
    const seen = [];
    for (const t of ds.traces) if (!seen.includes(t.condition)) seen.push(t.condition);
    // apo first, then by numeric concentration if present
    return seen.sort((a, b) => (a.startsWith('no') ? -1 : b.startsWith('no') ? 1 : (parseFloat(a) || 0) - (parseFloat(b) || 0)));
  }
  function setAxes(v) {
    axes = v;
    document.querySelectorAll('#axes button').forEach(b => b.setAttribute('aria-pressed', b.dataset.v === v));
    draw();
  }
  document.querySelectorAll('#axes button').forEach(b => b.onclick = () => { if (!b.disabled) setAxes(b.dataset.v); });
  function draw() {
    const pal = C.palette(), conds = conditions();
    const color = c => pal[conds.indexOf(c) % pal.length];
    $('cond-toggles').innerHTML = conds.map(c => `<button class="chip" data-c="${esc(c)}" aria-pressed="${!hidden.has(c)}" style="${hidden.has(c) ? 'opacity:.45' : ''}"><i style="display:inline-block;width:10px;height:10px;border-radius:3px;background:${color(c)}"></i> ${esc(c)} (${ds.traces.filter(t => t.condition === c).length})</button>`).join('');
    $('cond-toggles').querySelectorAll('[data-c]').forEach(b => b.onclick = () => { hidden.has(b.dataset.c) ? hidden.delete(b.dataset.c) : hidden.add(b.dataset.c); draw(); });
    const shown = ds.traces.filter(t => !hidden.has(t.condition));
    const pick = t => axes === 'fx' ? [t.x, t.f] : axes === 'ft' ? [t.t, t.f] : [t.t, t.x];
    const series = shown.filter(t => pick(t)[0]).map(t => { const [x, y] = pick(t); return { x, y, color: color(t.condition), opacity: shown.length > 10 ? 0.5 : 0.85, width: 1.2 }; });
    const xl = axes === 'fx' ? (shown[0]?.x_kind === 'position' ? 'position (nm)' : 'extension (nm)') : 'time (s)';
    const yl = axes === 'xt' ? 'extension (nm)' : 'force (pN)';
    $('plot').innerHTML = C.line({ id: 'v', series, xLabel: xl, yLabel: yl, height: 380, emptyText: 'Nothing to show for these axes' });
    $('plot-title').textContent = `${shown.length} trace${shown.length === 1 ? '' : 's'}`;
    $('plot-note').textContent = 'Pulling (or unlabelled) curves are shown; relaxation curves are in the source files. Colours follow the condition.';
  }
  $('dl-csv').onclick = () => {
    const rows = ['dataset,trace,condition,role,file,i,time_s,x_nm,force_pN'];
    ds.traces.filter(t => !hidden.has(t.condition)).forEach(t => t.f.forEach((f, i) => rows.push([ds.key, t.id, t.condition, t.role, `"${t.file}"`, i, t.t ? t.t[i] : '', t.x ? t.x[i] : '', f].join(','))));
    C.download(`smashbio-${ds.key}-display.csv`, `# display-downsampled traces from ${ds.url} (licence ${ds.license}); cite the original authors\n` + rows.join('\n'), 'text/csv');
  };
  document.querySelector('[data-svg="plot"]').onclick = () => C.exportSvg($('plot').querySelector('svg').outerHTML, 'smashbio-' + ds.key);
  document.addEventListener('smash:theme', () => { if (ds && ds.traces.length) draw(); });

  // ------------------------------------------------------------ your own file (browser only)
  const UNIT_RE = /^(.*?)\s*[([]\s*([^)\]]+?)\s*[)\]]\s*$/;
  const X_UNITS = { nm: 1, um: 1000, 'µm': 1000, m: 1e9, 'Å': 0.1, A: 0.1 };
  const F_UNITS = { pN: 1, nN: 1000, fN: 0.001, N: 1e12 };
  let own = null;
  function parse(text) {
    const lines = text.split(/\r?\n/).filter(l => l.trim() && !/^\s*#/.test(l));
    const delim = /\t/.test(lines[0]) ? '\t' : /;/.test(lines[0]) && !/,/.test(lines[0]) ? ';' : /,/.test(lines[0]) ? ',' : /\s+/;
    const split = l => l.trim().split(delim).map(s => s.trim().replace(/^"|"$/g, ''));
    const first = split(lines[0]);
    const header = first.some(s => s !== '' && isNaN(+s));
    const cols = header ? first : first.map((_, i) => `column ${i + 1}`);
    const data = (header ? lines.slice(1) : lines).map(split).filter(r => r.every(s => s === '' || !isNaN(+s)));
    return { cols, data };
  }
  function autoMap(cols) {
    const parts = cols.map(c => { const m = UNIT_RE.exec(c); return { name: m ? m[1] : c, unit: m ? m[2] : null }; });
    const fi = parts.map((p, i) => /\bforce\b|^f$/i.test(p.name) ? i : -1).filter(i => i >= 0);
    const xi = parts.map((p, i) => /extension|distance|separation|position|piezo/i.test(p.name) ? i : -1).filter(i => i >= 0);
    if (fi.length === 1 && xi.length === 1 && parts[fi[0]].unit in F_UNITS && parts[xi[0]].unit in X_UNITS) return { f: fi[0], x: xi[0], fu: parts[fi[0]].unit, xu: parts[xi[0]].unit };
    return null;
  }
  function plotOwn(m) {
    const x = own.data.map(r => +r[m.x] * X_UNITS[m.xu]), f = own.data.map(r => +r[m.f] * F_UNITS[m.fu]);
    $('own-chart').innerHTML = C.line({ id: 'own', series: [{ x, y: f, color: C.palette()[0], width: 1.3 }], xLabel: `${own.cols[m.x]} (nm)`, yLabel: `${own.cols[m.f]} (pN)`, height: 380 });
    $('own-status').innerHTML = `${x.length} points plotted, converted to nm and pN. Read locally; nothing was uploaded.`;
  }
  $('own-file').onchange = async e => {
    const file = e.target.files[0]; if (!file) return;
    if (file.size > 100e6) { $('own-status').textContent = 'File larger than 100 MB.'; return; }
    own = parse(await file.text());
    if (!own.data.length) { $('own-status').textContent = 'No numeric rows found.'; return; }
    const opt = own.cols.map((c, i) => `<option value="${i}">${esc(c)}</option>`).join('');
    $('own-x').innerHTML = opt; $('own-y').innerHTML = opt;
    $('own-xu').innerHTML = Object.keys(X_UNITS).map(u => `<option>${u}</option>`).join('');
    $('own-yu').innerHTML = Object.keys(F_UNITS).map(u => `<option>${u}</option>`).join('');
    const m = autoMap(own.cols);
    $('own-map').hidden = false;
    if (m) {
      $('own-x').value = m.x; $('own-y').value = m.f; $('own-xu').value = m.xu; $('own-yu').value = m.fu;
      plotOwn(m);
    } else {
      $('own-status').innerHTML = `Found ${own.cols.length} columns and ${own.data.length} rows. The header does not name the force and extension columns with units unambiguously, so please choose them and their units.`;
    }
  };
  $('own-plot').onclick = () => own && plotOwn({ x: +$('own-x').value, f: +$('own-y').value, xu: $('own-xu').value, fu: $('own-yu').value });

  document.addEventListener('DOMContentLoaded', loadIndex);
})();
